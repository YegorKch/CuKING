def norm(ing):
    prod, qty, unit, *rest = ing
    return prod, qty, unit, (rest[0] if rest else True)


def techniques(d):
    seen = []
    for _, _, t in d["steps"]:
        if t and t not in seen:
            seen.append(t)
    return seen


def yesno(v):
    return "ДА" if v else "НЕТ"


def check():
    ids = [d["id"] for d in DISHES]
    assert len(ids) == len(set(ids)), "дубли ID"
    for d in DISHES:
        assert d["cat"] in CATEGORIES, d["id"]
        assert all(t in TAGS for t in d["tags"]), d["id"]
        assert (d["garnish"] is None) == (d["cat"] != "Горячее"), d["id"]
        for ing in d["ingredients"]:
            _, qty, unit, _ = norm(ing)
            assert unit in UNITS, (d["id"], ing)
            assert (qty is None) == (unit in ("по вкусу", "щепотка")), (d["id"], ing)
        for _, _, t in d["steps"]:
            assert t == "" or t in TECHNIQUE, (d["id"], t)


def build_xlsx(path):
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment

    wb = Workbook()
    bold = Font(bold=True)

    def sheet(title, header, rows, first=False):
        ws = wb.active if first else wb.create_sheet()
        ws.title = title
        ws.append(header)
        for c in ws[1]:
            c.font = bold
        for r in rows:
            ws.append(r)
        ws.freeze_panes = "A2"
        for col in ws.columns:
            width = max(len(str(c.value or "")) for c in col)
            ws.column_dimensions[col[0].column_letter].width = min(max(width + 2, 8), 60)
        return ws

    sheet("Блюда",
          ["ID", "Название", "Описание", "Категория", "Нужен_гарнир", "Время_мин", "Порций",
           "Техника", "Сложность", "Теги", "Активно"],
          [[d["id"], d["name"], d["desc"], d["cat"],
            "" if d["garnish"] is None else yesno(d["garnish"]),
            d["time"], d["portions"], ", ".join(techniques(d)), d["diff"],
            ", ".join(d["tags"]), "ДА"] for d in DISHES],
          first=True)

    sheet("Ингредиенты", ["ID_блюда", "Продукт", "Кол-во", "Ед.", "Обязательный"],
          [[d["id"], p, q, u, yesno(r)]
           for d in DISHES for p, q, u, r in map(norm, d["ingredients"])])

    ws = sheet("Шаги", ["ID_блюда", "Номер", "Заголовок", "Текст", "Техника"],
               [[d["id"], i, title, text, tech]
                for d in DISHES for i, (title, text, tech) in enumerate(d["steps"], 1)])
    ws.column_dimensions["D"].width = 90
    for row in ws.iter_rows(min_row=2):
        row[3].alignment = Alignment(wrap_text=True, vertical="top")

    sheet("История", ["ID_записи", "Дата", "ID_блюда", "ID_гарнира", "Тип", "Оценка_Егор", "Оценка_Арина"], [])

    ws = wb.create_sheet("Справочники")
    blocks = [("Категория", [[c] for c in CATEGORIES], 1),
              ("Колода", [list(x) for x in DECKS], 3),
              ("Техника", [[t] for t in TECHNIQUE], 6),
              ("Единица", [[u] for u in UNITS], 8),
              ("Тег", [[t] for t in TAGS], 10)]
    ws.cell(1, 4, "Категории_колоды").font = bold
    for title, rows, col in blocks:
        ws.cell(1, col, title).font = bold
        for r, values in enumerate(rows, 2):
            for k, v in enumerate(values):
                ws.cell(r, col + k, v)
    for letter, w in zip("ABCDEFGHIJ", [12, 2, 12, 18, 2, 16, 2, 10, 2, 14]):
        ws.column_dimensions[letter].width = w

    wb.save(path)


def fmt_qty(q):
    if q is None:
        return ""
    return str(q).replace(".", ",") if isinstance(q, float) else str(q)


def build_md(path):
    out = ["# Рецепты CuKING v1", "",
           "Сгенерировано из `data/recipes.py`. Базово — на 4 порции (лазанья — на 6).",
           "Правки удобнее вносить прямо в Google-таблицу после импорта.", ""]
    sections = [("Супы", "Суп"), ("Горячее", "Горячее"), ("Гарниры", "Гарнир")]
    for title, cat in sections:
        out += [f"## {title}", ""]
        for d in (x for x in DISHES if x["cat"] == cat):
            meta = [f"{d['time']} мин", f"{d['portions']} порц.", f"сложность {d['diff']}",
                    " · ".join(techniques(d)) or "без техники"]
            if d["garnish"] is not None:
                meta.append("нужен гарнир" if d["garnish"] else "без гарнира")
            if d["tags"]:
                meta.append(", ".join(d["tags"]))
            out += [f"### {d['name']}", "", f"*{d['desc']}*", "", " · ".join(meta), "", "**Ингредиенты**", ""]
            ings = list(map(norm, d["ingredients"]))
            for p, q, u, r in ings:
                if r:
                    out.append(f"- {p} — {fmt_qty(q)} {u}".replace("—  ", "— "))
            opt = [x for x in ings if not x[3]]
            if opt:
                out += ["", "*По желанию:*", ""]
                out += [f"- {p} — {fmt_qty(q)} {u}".replace("—  ", "— ") for p, q, u, _ in opt]
            out += ["", "**Шаги**", ""]
            for i, (t, text, tech) in enumerate(d["steps"], 1):
                suffix = f" *({tech})*" if tech else ""
                out.append(f"{i}. **{t}.** {text}{suffix}")
            out.append("")
    Path(path).write_text("\n".join(out), encoding="utf-8")


